"""Generates bindings/go/types_gen.go from schema/provider.schema.json."""
import json, pathlib, re, subprocess, sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
schema = json.load(open(root / "schema/provider.schema.json"))
defs = schema["$defs"]
INITIALISMS = {"id": "ID", "url": "URL", "json": "JSON", "ttl": "TTL", "ns": "NS", "api": "API", "uri": "URI"}
OPAQUE = {"raw", "vendor_state", "body", "event", "dialect"}


def camel(name):
    return "".join(INITIALISMS.get(p, p[:1].upper() + p[1:]) for p in name.split("_") if p)


def const_name(type_name, value):
    return type_name + camel(re.sub(r"[^a-z0-9]+", "_", value.lower()))


def is_open_enum(node):
    options = node.get("anyOf") or []
    return len(options) == 2 and "enum" in options[0] and options[1] == {"type": "string"}


def nullable(node):
    options = node.get("anyOf") or []
    return len(options) == 2 and options[1] == {"type": "null"}


extra_types = []
enums = {}
parent_of = {v["$ref"].rsplit("/", 1)[-1]: name for name, node in defs.items() if "oneOf" in node and "properties" not in node for v in node["oneOf"] if "$ref" in v}


def go_type(node, owner, field):
    if "$ref" in node:
        name = node["$ref"].rsplit("/", 1)[-1]
        name = parent_of.get(name, name)
        target = defs[name]
        if is_open_enum(target) or target.get("type") == "string":
            return name, False
        if target.get("type") == "object" and "properties" not in target:
            return name, False
        return name, True
    if "const" in node:
        return "string", False
    if "enum" in node or is_open_enum(node):
        values = node.get("enum") or node["anyOf"][0]["enum"]
        type_name = owner + camel(field)
        enums[type_name] = (values, f"{owner}.{field}")
        return type_name, False
    if nullable(node):
        inner, _ = go_type(node["anyOf"][0], owner, field)
        return inner, True
    if "anyOf" in node or ("oneOf" in node and "properties" not in node):
        return "any", False
    kind = node.get("type")
    if kind == "array":
        inner, _ = go_type(node.get("items", {}), owner, field)
        return f"[]{inner}", False
    if kind == "object":
        if "properties" in node:
            name = owner + camel(field)
            extra_types.append((name, node))
            return name, True
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            inner, _ = go_type(extra, owner, field)
            return f"map[string]{inner}", False
        return "map[string]any", False
    if field in OPAQUE or kind is None:
        return "json.RawMessage", False
    return {"string": ("string", False), "integer": ("int64", True), "number": ("float64", True), "boolean": ("bool", True), "null": ("any", False)}[kind]


def comment(name, text):
    text = (text or "").strip()
    return f"// {name}: {text}" if text else f"// {name} is one {name} document."


def struct(name, node, description=None):
    lines = [comment(name, node.get("description") if description is None else description), f"type {name} struct {{"]
    required = set(node.get("required", []))
    for field, prop in node["properties"].items():
        typ, ptr = go_type(prop, name, field)
        if field not in required and ptr:
            typ = "*" + typ
        if nullable(prop):
            typ = "*" + typ.lstrip("*")
            tag = f'json:"{field}"'
        elif field in required:
            tag = f'json:"{field}"'
        else:
            tag = f'json:"{field},omitempty"'
        if prop.get("description"):
            lines.append(f"\t// {prop['description'].strip()}")
        lines.append(f"\t{camel(field)} {typ} `{tag}`")
    lines.append("}")
    return "\n".join(lines)


def variant(v):
    return defs[v["$ref"].rsplit("/", 1)[-1]] if "$ref" in v else v


def merged(name, variants, description):
    props = {}
    kinds = sorted({variant(v)["properties"]["type"]["const"] for v in variants})
    for v in variants:
        for field, prop in variant(v)["properties"].items():
            if field == "type":
                props["type"] = {"type": "string", "description": "One of " + ", ".join(kinds) + "; it selects the fields that apply"}
            else:
                props.setdefault(field, prop)
    return struct(name, {"properties": props, "required": ["type"]}, description)


out = ["// Code generated by scripts/gen_go_types.py from schema/provider.schema.json; DO NOT EDIT.", "", "package ducktape", "", 'import "encoding/json"', ""]
variant_names = set(parent_of)
for name, node in defs.items():
    if name in variant_names:
        continue
    if node.get("type") == "object" and "properties" in node:
        out.append(struct(name, node))
    elif "oneOf" in node:
        out.append(merged(name, node["oneOf"], (node.get("description") or "").strip() + "; the variants are merged into one struct"))
    elif is_open_enum(node) or node.get("type") == "string":
        out.append(comment(name, node.get("description") or "open string enum"))
        out.append(f"type {name} string")
        if is_open_enum(node):
            out.append("const (")
            for v in node["anyOf"][0]["enum"]:
                out.append(f"\t{const_name(name, v)} {name} = {json.dumps(v)}")
            out.append(")")
    elif node.get("type") == "object":
        typ, _ = go_type(node, name, "")
        out.append(comment(name, node.get("description")))
        out.append(f"type {name} = {typ}")
    else:
        out.append(comment(name, "untyped"))
        out.append(f"type {name} = any")
    out.append("")
seen = set()
while extra_types:
    name, node = extra_types.pop(0)
    if name in seen:
        continue
    seen.add(name)
    out.append(struct(name, node, node.get("description") or "nested object"))
    out.append("")
for type_name, (values, origin) in enums.items():
    out.append(f"// {type_name}: open enum of {origin}.")
    out.append(f"type {type_name} string")
    out.append("const (")
    for v in values:
        out.append(f"\t{const_name(type_name, v)} {type_name} = {json.dumps(v)}")
    out.append(")")
    out.append("")
target = root / "bindings/go/types_gen.go"
text = "\n".join(out).rstrip() + "\n"
text = subprocess.run(["gofmt"], input=text, capture_output=True, text=True, check=True).stdout
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text() == text else "types_gen.go is out of date; run python scripts/gen_go_types.py .")
target.write_text(text)
print(f"wrote {target}")
