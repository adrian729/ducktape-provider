"""Generates bindings/js/schema.d.ts from schema/provider.schema.json."""
import json, pathlib, sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
schema = json.load(open(root / "schema/provider.schema.json"))
defs = schema["$defs"]


def doc(node, indent=""):
    text = (node.get("description") or "").strip().replace("*/", "* /")
    return f"{indent}/** {text} */\n" if text else ""


def literal(value):
    return json.dumps(value)


def is_open_enum(node):
    options = node.get("anyOf") or []
    return len(options) == 2 and "enum" in options[0] and options[1] == {"type": "string"}


def ts(node, indent):
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return literal(node["const"])
    if "enum" in node:
        return " | ".join(literal(v) for v in node["enum"])
    if is_open_enum(node):
        return " | ".join(literal(v) for v in node["anyOf"][0]["enum"]) + " | (string & {})"
    if "anyOf" in node or ("oneOf" in node and "properties" not in node):
        options = node.get("anyOf") or node["oneOf"]
        return " | ".join(paren(ts(o, indent)) for o in options)
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({**node, "type": k}, indent) for k in kind)
    if kind == "array":
        item = ts(node.get("items", {}), indent)
        return f"{item}[]" if " " not in item else f"Array<{item}>"
    if kind == "object":
        if "properties" in node:
            return object_body(node, indent)
        extra = node.get("additionalProperties")
        if extra is False:
            return "Record<string, never>"
        if isinstance(extra, dict) and extra:
            return f"Record<string, {ts(extra, indent)}>"
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def paren(text):
    return f"({text})" if " | " in text and not text.startswith("{") else text


def object_body(node, indent):
    inner = indent + "  "
    required = set(node.get("required", []))
    lines = []
    for name, prop in node["properties"].items():
        lines.append(doc(prop, inner) + f"{inner}{name}{'' if name in required else '?'}: {ts(prop, inner)};")
    extra = node.get("additionalProperties")
    if isinstance(extra, dict):
        lines.append(f"{inner}[key: string]: {ts(extra, inner)};")
    return "{\n" + "\n".join(lines) + f"\n{indent}}}"


out = ["// Generated by scripts/gen_dts.py from schema/provider.schema.json; do not edit.", ""]
for name, node in defs.items():
    if node.get("type") == "object" and "properties" in node:
        out.append(doc(node) + f"export interface {name} {object_body(node, '')}")
    else:
        out.append(doc(node) + f"export type {name} = {ts(node, '')};")
    out.append("")
target = root / "bindings/js/schema.d.ts"
text = "\n".join(out)
if "--check" in sys.argv:
    sys.exit(0 if target.read_text() == text else "schema.d.ts is out of date; run python scripts/gen_dts.py .")
target.write_text(text)
print(f"wrote {target} ({len(defs)} definitions)")
